// Every card shares one size so the README can let them wrap: two per row on
// desktop, one per row on mobile, all at the same scale.
const CARD_WIDTH = 400;
const CARD_HEIGHT = 154;

// Extensions of files changed in pull requests; unlisted ones count as Other.
const EXTENSION_LANGUAGES = {
  ts: 'TypeScript', tsx: 'TypeScript', mts: 'TypeScript', cts: 'TypeScript',
  js: 'JavaScript', jsx: 'JavaScript', mjs: 'JavaScript', cjs: 'JavaScript',
  java: 'Java', go: 'Go', py: 'Python', rs: 'Rust', swift: 'Swift', rb: 'Ruby', kt: 'Kotlin', cs: 'C#',
  c: 'C', h: 'C', cc: 'C++', cpp: 'C++', hpp: 'C++', sh: 'Shell', ps1: 'PowerShell', psm1: 'PowerShell',
  tf: 'HCL', bicep: 'Bicep', sql: 'SQL', html: 'HTML', css: 'CSS', scss: 'SCSS', vue: 'Vue', svelte: 'Svelte',
  astro: 'Astro', md: 'Markdown', markdown: 'Markdown', mdx: 'MDX', yml: 'YAML', yaml: 'YAML', json: 'JSON',
  toml: 'TOML', y: 'Yacc',
};
const FILENAME_LANGUAGES = { Dockerfile: 'Dockerfile', Makefile: 'Makefile' };
// GitHub's language stats leave out generated files. Linguist finds lockfiles
// and node_modules/ by path, and generated Go by a line in the first 40 that
// starts with "// Code generated", such as "// Code generated by goyacc DO NOT
// EDIT.". yarn.lock and go.sum are lockfiles too, though linguist counts them.
const LOCKFILES = new Set([
  'package-lock.json', 'npm-shrinkwrap.json', 'pnpm-lock.yaml', 'yarn.lock', 'bun.lock', 'bun.lockb', 'deno.lock',
  'go.sum', 'Gopkg.lock', 'Cargo.lock', 'composer.lock', 'poetry.lock', 'uv.lock', 'Pipfile.lock', '.terraform.lock.hcl',
]);
const GENERATED_HEADER = /^\/\/ Code generated /;
const GENERATED_SCAN_LINES = 40;
const FONT = "-apple-system, 'Segoe UI', Helvetica, Arial, sans-serif";

async function request(url, init = {}) {
  const response = await fetch(url, {
    ...init,
    headers: { authorization: `Bearer ${TOKEN}`, accept: 'application/vnd.github+json', ...init.headers },
  });
  if (!response.ok) {
    throw new Error(`${init.method ?? 'GET'} ${url} failed: ${response.status} ${await response.text()}`);
  }
  return response.json();
}

async function graphql(query, variables) {
  const { data, errors } = await request('https://api.github.com/graphql', {
    method: 'POST',
    body: JSON.stringify({ query, variables }),
  });
  if (errors) {
    throw new Error(JSON.stringify(errors));
  }
  return data;
}

async function searchPullRequests(filter) {
  const query = `query($q: String!, $after: String) {
    search(type: ISSUE, query: $q, first: 100, after: $after) {
      issueCount
      pageInfo { hasNextPage endCursor }
      nodes { ... on PullRequest { number repository { nameWithOwner } } }
    }
  }`;
  const repositories = new Set();
  const pulls = [];
  let after = null;
  let count = 0;
  do {
    const { search } = await graphql(query, { q: `is:pr author:${LOGIN} -user:${LOGIN} ${filter}`, after });
    count = search.issueCount;
    for (const node of search.nodes) {
      repositories.add(node.repository.nameWithOwner);
      pulls.push({ repository: node.repository.nameWithOwner, number: node.number });
    }
    after = search.pageInfo.hasNextPage ? search.pageInfo.endCursor : null;
  } while (after);
  return { count, repositories, pulls };
}

async function listOwnRepositories() {
  const base = 'https://api.github.com/user/repos?affiliation=owner&visibility=all';
  const repositories = [];
  for (let page = 1; ; page++) {
    const batch = await request(`${base}&per_page=100&page=${page}`);
    repositories.push(...batch);
    if (batch.length < 100) {
      return repositories.filter((repository) => !repository.fork);
    }
  }
}

async function countRepositoryLanguages() {
  const totals = new Map();
  for (const repository of await listOwnRepositories()) {
    const languages = await request(repository.languages_url);
    for (const [language, bytes] of Object.entries(languages)) {
      totals.set(language, (totals.get(language) ?? 0) + bytes);
    }
  }
  return topLanguages(totals);
}

function fileLanguage(path) {
  const name = path.split('/').pop();
  const extension = name.includes('.') ? name.split('.').pop().toLowerCase() : '';
  return FILENAME_LANGUAGES[name] ?? EXTENSION_LANGUAGES[extension] ?? 'Other';
}

// Stops reading a changed file once its first lines as of the pull request head
// are in, so a generated file of several megabytes is not downloaded in full.
async function isGenerated(file) {
  const segments = file.filename.split('/');
  if (LOCKFILES.has(segments.at(-1)) || segments.includes('node_modules')) {
    return true;
  }
  if (file.status === 'removed') {
    return false;
  }
  const response = await fetch(file.contents_url, {
    headers: { authorization: `Bearer ${TOKEN}`, accept: 'application/vnd.github.raw' },
  });
  if (!response.ok) {
    throw new Error(`GET ${file.contents_url} failed: ${response.status} ${await response.text()}`);
  }
  const reader = response.body.getReader();
  const decoder = new TextDecoder();
  let text = '';
  while (text.split('\n').length <= GENERATED_SCAN_LINES) {
    const { done, value } = await reader.read();
    if (done) {
      break;
    }
    text += decoder.decode(value, { stream: true });
  }
  await reader.cancel();
  return text.split('\n').slice(0, GENERATED_SCAN_LINES).some((line) => GENERATED_HEADER.test(line));
}

// Weighs each language by the lines added and deleted in merged pull requests,
// leaving out generated files.
async function countPullRequestLanguages(pulls) {
  const totals = new Map();
  for (const { repository, number } of pulls) {
    for (let page = 1; ; page++) {
      const files = await request(`https://api.github.com/repos/${repository}/pulls/${number}/files?per_page=100&page=${page}`);
      for (const file of files) {
        if (await isGenerated(file)) {
          console.log(`Skipped generated file ${repository}#${number} ${file.filename}`);
          continue;
        }
        const language = fileLanguage(file.filename);
        totals.set(language, (totals.get(language) ?? 0) + file.additions + file.deletions);
      }
      if (files.length < 100) {
        break;
      }
    }
  }
  return topLanguages(totals);
}

function topLanguages(totals) {
  const sum = [...totals.values()].reduce((a, b) => a + b, 0);
  return [...totals.entries()]
    .sort((a, b) => b[1] - a[1])
    .slice(0, TOP_LANGUAGES)
    .map(([name, bytes]) => ({ name, share: bytes / sum }));
}

function escapeXml(text) {
  return text.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;' })[c]);
}

function card(width, height, title, theme, body) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-label="${escapeXml(title)}">
  <rect x="0.5" y="0.5" width="${width - 1}" height="${height - 1}" rx="9.5" fill="${theme.bg}" stroke="${theme.border}"/>
  <text x="24" y="36" font-family="${FONT}" font-size="15" font-weight="600" fill="${theme.accent}">${escapeXml(title)}</text>
${body}
</svg>
`;
}

function statsCard(stats, theme) {
  const columns = [
    ['MERGED', stats.merged],
    ['REPOS', stats.repositories],
  ];
  const width = CARD_WIDTH;
  const step = (width - 48) / columns.length;
  const body = columns.map(([label, value], i) => {
    const x = 24 + step * i + step / 2;
    return `  <text x="${x}" y="98" text-anchor="middle" font-family="${FONT}" font-size="34" font-weight="700" fill="${theme.text}">${value}</text>
  <text x="${x}" y="124" text-anchor="middle" font-family="${FONT}" font-size="11" font-weight="600" letter-spacing="1" fill="${theme.sub}">${label}</text>`;
  }).join('\n');
  return card(width, CARD_HEIGHT, 'External pull requests', theme, body);
}

// Draws a donut of language slices over a glowing, grainy background. Each
// slice is a dash of one circle's stroke, starting at 12 o'clock, with a small
// gap so that thin slices stay distinguishable. The legend lists every language
// with a bar scaled to the largest share.
function languagesCard(title, languages, theme, note = '') {
  const [width, height] = [CARD_WIDTH, 186];
  const [cx, cy, radius, thickness, gap] = [88, 114, 44, 14, 1.5];
  const circumference = 2 * Math.PI * radius;
  const total = languages.reduce((a, l) => a + l.share, 0);
  const largest = Math.max(...languages.map((l) => l.share));
  let offset = 0;
  languages = languages.map((language, i) => ({ ...language, color: theme.palette[i % theme.palette.length] }));
  const slices = languages.map(({ share, color }) => {
    const length = circumference * share / total;
    const dash = Math.max(length - gap, 1);
    const slice = `    <circle cx="${cx}" cy="${cy}" r="${radius}" fill="none" stroke="${color}" stroke-width="${thickness}" stroke-dasharray="${dash.toFixed(2)} ${(circumference - dash).toFixed(2)}" stroke-dashoffset="${(-offset).toFixed(2)}"/>`;
    offset += length;
    return slice;
  }).join('\n');
  const [legendX, legendRight, legendTop, rowHeight] = [176, width - 24, 66, 20];
  const legend = languages.map(({ name, share, color }, i) => {
    const y = legendTop + i * rowHeight;
    const barWidth = (legendRight - legendX - 14) * share / largest;
    return `  <circle cx="${legendX + 4}" cy="${y - 4}" r="4" fill="${color}" stroke="${theme.border}" stroke-width="0.5"/>
  <text x="${legendX + 14}" y="${y}" font-family="${FONT}" font-size="12" fill="${theme.text}">${escapeXml(name)}</text>
  <text x="${legendRight}" y="${y}" text-anchor="end" font-family="${FONT}" font-size="12" font-weight="600" fill="${theme.accent}">${(share * 100).toFixed(1)}%</text>
  <rect x="${legendX + 14}" y="${y + 4}" width="${legendRight - legendX - 14}" height="2" rx="1" fill="${theme.track}"/>
  <rect x="${legendX + 14}" y="${y + 4}" width="${barWidth.toFixed(2)}" height="2" rx="1" fill="${color}"/>`;
  }).join('\n');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-label="${escapeXml(title)}">
  <defs>
    <clipPath id="card"><rect x="0.5" y="0.5" width="${width - 1}" height="${height - 1}" rx="9.5"/></clipPath>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="${theme.bg}"/>
      <stop offset="1" stop-color="${theme.bgEdge}"/>
    </linearGradient>
    <radialGradient id="glow" cx="${cx}" cy="${cy}" r="150" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="${theme.glow}" stop-opacity="${theme.glowOpacity}"/>
      <stop offset="1" stop-color="${theme.glow}" stop-opacity="0"/>
    </radialGradient>
    <filter id="grain" x="0" y="0" width="100%" height="100%">
      <feTurbulence type="fractalNoise" baseFrequency="0.9" numOctaves="2" stitchTiles="stitch"/>
      <feColorMatrix values="0 0 0 0 0.851  0 0 0 0 0.671  0 0 0 0 0.459  0 0 0 ${theme.grain} 0"/>
    </filter>
  </defs>
  <g clip-path="url(#card)">
    <rect width="${width}" height="${height}" fill="url(#bg)"/>
    <rect width="${width}" height="${height}" fill="url(#glow)"/>
    <rect width="${width}" height="${height}" filter="url(#grain)"/>
  </g>
  <rect x="0.5" y="0.5" width="${width - 1}" height="${height - 1}" rx="9.5" fill="none" stroke="${theme.border}"/>
  <text x="24" y="36" font-family="${FONT}" font-size="15" font-weight="600" fill="${theme.accent}">${escapeXml(title)}</text>
  <text x="${width - 24}" y="36" text-anchor="end" font-family="${FONT}" font-size="11" fill="${theme.sub}">${escapeXml(note)}</text>
  <g transform="rotate(-90 ${cx} ${cy})">
${slices}
  </g>
${legend}
</svg>
`;
}

const [merged, repositoryLanguages] = await Promise.all([
  searchPullRequests('is:merged'),
  HAS_USER_TOKEN ? countRepositoryLanguages() : null,
]);
const pullRequestLanguages = await countPullRequestLanguages(merged.pulls);
const stats = { merged: merged.count, repositories: merged.repositories.size };
console.log(JSON.stringify({ ...stats, mergedRepositories: [...merged.repositories], repositoryLanguages, pullRequestLanguages }, null, 2));

await mkdir('images', { recursive: true });
for (const [name, theme] of Object.entries(THEMES)) {
  await writeFile(`images/stats-${name}.svg`, statsCard(stats, theme));
  await writeFile(`images/pr-languages-${name}.svg`, languagesCard('Languages in merged pull requests', pullRequestLanguages, theme, `${stats.merged} PRs · ${stats.repositories} repos`));
  if (repositoryLanguages) {
    await writeFile(`images/languages-${name}.svg`, languagesCard('Languages in my repositories', repositoryLanguages, theme));
  }
}
if (!repositoryLanguages) {
  console.log('STATS_TOKEN is not set; kept the existing language card');
}
